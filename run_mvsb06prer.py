def fmt(x, nd=4):
    if x == float("inf"):
        return "inf"
    return f"{x:.{nd}f}"


def mp(flag):
    return "PASS" if flag else "FAIL"


def wilson_lower(k, n, z=Z95):
    """One-sided Wilson 95% LOWER bound on the binomial proportion."""
    if n <= 0:
        return 0.0
    p = k / n
    denom = 1.0 + z * z / n
    center = (p + z * z / (2.0 * n)) / denom
    half = z * math.sqrt((p * (1.0 - p) + z * z / (4.0 * n)) / n) / denom
    return max(0.0, center - half)


def mean_ucb(xs, alpha=0.05):
    """One-sided (1-alpha) UPPER t-CI on the mean of xs."""
    xs = np.asarray(xs, dtype=np.float64)
    n = len(xs)
    if n == 0:
        return float("inf")
    m = float(xs.mean())
    s = float(xs.std(ddof=1)) if n > 1 else 0.0
    tcrit = float(t_dist.ppf(1.0 - alpha, max(n - 1, 1)))
    return m + tcrit * s / math.sqrt(n)


def delta_t(t):
    return 6.0 * DELTA_EP / (math.pi * math.pi * t * t)


def base_anchor(cr, base, x, h, Qp):
    """Budget-aware base action + its Q^{pi_b} under the matched oracle.
    Clamps to STOP when the nominal base action is unaffordable at h
    (mirrors CPI.decide's anchor clamp — 012 §5 budget-aware semantics)."""
    om = cr.pl.omega(x)
    R0 = cr.pl.r_stop(x)
    a_b = base.act(cr.pl, x, om, h=h)
    if a_b is not None and a_b not in Qp:
        a_b = None
    qb = R0 if a_b is None else Qp[a_b]
    return a_b, qb


def apply_action(cr, x, h, action, world):
    """Apply (i, r2) on `world`: returns (x2, h2) or None if infeasible."""
    i, r2 = action
    r_old, _ = z_decode_b(cr._z_digit(x, i))
    c = cr.b_h + (r2 - r_old)
    if c > h + 1e-9:
        return None
    x2, _om2 = cr._apply(x, cr.pl.omega(x), i, r2, world.cells)
    return x2, h - c


def random_trajectories(cr, rng, n, max_steps=3):
    """Set A: random legal feedback sequences with REAL cost deduction.
    Returns the (x, h, t) decision states visited, deduped."""
    seen = set()
    out = []
    for _ in range(n):
        x, h, t = 0, H0, 1
        states = [(x, h, t)]
        for _s in range(max_steps):
            acts = cr.feasible_actions(x, h)
            if not acts:
                break
            a = acts[int(rng.integers(0, len(acts)))]
            world = LatentWorld(cr, x)
            res = apply_action(cr, x, h, a, world)
            if res is None:
                break
            x, h = res
            t += 1
            states.append((x, h, t))
        for st in states:
            if st not in seen:
                seen.add(st)
                out.append(st)
    return out


def occupancy_episodes(cr, base, rng, n_ep, w_ep, max_steps=6):
    """Set B: on-policy occupancy — episodes under the FROZEN policy
    (SNR base + CPI betting acquisition at w_ep).  Returns deduped
    (x, h, t) decision states."""
    quants = cr.quants
    seen = set()
    out = []
    for e in range(n_ep):
        x, h, t = 0, H0, 1
        states = [(x, h, t)]
        for _s in range(max_steps):
            acts = cr.feasible_actions(x, h)
            if not acts:
                break
            cpi = CPI(quants, MU_M, MU_F, BH, base, levels=cr.levels,
                      delta_c=1.0, seed=3, cs_mode="betting")
            cpi.cr.rng = np.random.default_rng(31000 + 1000 * e + t)
            a, _info = cpi.decide(x, h, delta_t=delta_t(t), max_worlds=w_ep)
            if a is None:
                break
            world = LatentWorld(cr, x)
            res = apply_action(cr, x, h, a, world)
            if res is None:
                break
            x, h = res
            t += 1
            states.append((x, h, t))
        for st in states:
            if st not in seen:
                seen.add(st)
                out.append(st)
    return out


